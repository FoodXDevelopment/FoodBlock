// Go: sdk/go/door_gen.go. Every op as one unexported typed function, door + the op's name in PascalCase (doorMatches), over core.go's
// ask and must. Missing optional arguments go to the core as null: "" for text, suite and time; nil for an int pointer, an object, a
// block, a json value and a list; false for a bool. A block or an object is taken as any (a Block, a message, a struct or a map);
// a list that must be there is never null. An op whose answer is a block, an object or a json value is generic in that answer (T), so the
// caller reads it as the Block, struct, map or value it wants (a message part is a map, not a Block).
const { camel, pascal } = require('./table.cjs')

const KEYWORDS = new Set(['type', 'func', 'map', 'range', 'go', 'var', 'const', 'default', 'chan', 'interface', 'package', 'import', 'return', 'switch', 'select', 'case', 'struct', 'fallthrough', 'goto', 'defer', 'else', 'for', 'if', 'break', 'continue'])
const name = (a) => { const n = camel(a.name); return KEYWORDS.has(n) ? n.slice(0, 3) : n }

const PARAM = { text: 'string', time: 'string', suite: 'string', int: 'int64', bool: 'bool', block: 'any', object: 'any', json: 'any', blocks: '[]Block', strings: '[]string', arrivals: 'map[string]string' }
const type = (a) => (a.type === 'int' && a.optional ? '*int64' : PARAM[a.type])
const sent = (a) => {
  const n = name(a)
  if (a.type === 'suite' || (a.optional && (a.type === 'text' || a.type === 'time'))) return `nilIfEmpty(${n})`
  if (a.optional && a.type === 'bool') return `nilIfFalse(${n})`
  if (!a.optional && (a.type === 'blocks' || a.type === 'strings')) return `plural(${n})`
  return n
}

const RESULT = { text: 'string', bool: 'bool', int: 'int64', blocks: '[]Block', strings: '[]string', refusals: '[]Finding' }
const listed = (r) => r === 'blocks' || r === 'strings' || r === 'refusals'

// The `!` marker is the whole failure rule: with it an op answers (T, error) through ask; without it, T through must, which stops
// the call on any failure.
function emitOp(o) {
  const generic = ['object', 'json', 'block'].includes(o.result)
  let t = generic ? 'T' : RESULT[o.result]
  if (o.nullable && !generic && !listed(o.result)) t = `*${t}`
  const params = o.args.map((a) => `${name(a)} ${type(a)}`).join(', ')
  const call = [`"${o.op}"`, ...o.args.map(sent)].join(', ')
  const sig = `${o.fails ? `(${t}, error)` : t}`
  const head = `// ${`door${pascal(o.op)}`} is the door's ${o.op}(${o.args.map((a) => a.name + (a.optional ? '?' : '')).join(', ')}) -> ${o.result}${o.nullable ? '?' : ''}${o.fails ? ' !' : ''}.\nfunc door${pascal(o.op)}${generic ? '[T any]' : ''}(${params}) ${sig} {\n`
  const fn = o.fails ? 'ask' : 'must'
  const ask = `${fn}[${t}](${call})`
  if (listed(o.result) && !o.nullable) {
    return o.fails ? `${head}\tout, err := ${ask}\n\treturn plural(out), err\n}\n` : `${head}\treturn plural(${ask})\n}\n`
  }
  return `${head}\treturn ${ask}\n}\n`
}

function emit(ops) {
  return `// Generated by tools/gen-door.cjs from sdk/door.table. Do not edit.
// Every op of the core's door (sdk/rust/src/door.rs) as one typed function. An op marked ! in the table answers (T, error) through
// ask; any other answers T through must, which panics on a failure. A block, object or json answer is read as T, the caller's shape.

package foodblock

${ops.map(emitOp).join('\n')}`
}
module.exports = { file: 'sdk/go/door_gen.go', emit }
