// JavaScript: sdk/javascript/src/door.cjs. Every op as a function of its arguments by position. A list of blocks is any collection
// (list()); a missing optional argument is null. The core's failures throw (core.cjs).
const { camel } = require('./table.cjs')

const normal = (a) => (a.type === 'blocks' ? (a.optional ? `${a.name} == null ? null : list(${a.name})` : `list(${a.name})`) : a.optional || a.type === 'suite' ? `${a.name} ?? null` : a.name)

function emit(ops) {
  const lines = ops.map((o) => {
    const params = o.args.map((a) => a.name).join(', ')
    const call = [`'${o.op}'`, ...o.args.map(normal)].join(', ')
    return `  ${camel(o.op)}: (${params}) => call(${call}),`
  })
  return `// Generated by tools/gen-door.cjs from sdk/door.table. Do not edit.
// Every op of the core's door as a function of its arguments by position (src/door.rs).
const { call, list } = require('./core.cjs')

module.exports = {
${lines.join('\n')}
}
`
}
module.exports = { file: 'sdk/javascript/src/door.cjs', emit }
