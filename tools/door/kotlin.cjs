// Kotlin: sdk/kotlin/.../Door.kt. Every op as a function of JsonElement arguments by position; the SDK's own wrappers (Folds.kt,
// FoodBlock.kt, Cbor.kt) build those from their typed arguments. A `?` argument defaults to JsonNull, and a trailing missing one
// is left out of the call (as the table says); the core's failures throw (Native.invoke).
const { camel } = require('./table.cjs')

const HARD = new Set(['as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if', 'in', 'interface', 'is', 'null', 'object', 'package', 'return', 'super', 'this', 'throw', 'true', 'try', 'typealias', 'typeof', 'val', 'var', 'when', 'while'])
const id = (s) => { const c = camel(s); return HARD.has(c) ? `\`${c}\`` : c }

function emit(ops) {
  const fns = ops.map((o) => {
    const params = o.args.map((a) => `${id(a.name)}: JsonElement${a.optional ? ' = JsonNull' : ''}`).join(', ')
    const required = o.args.filter((a) => !a.optional).length
    const call = [`"${o.op}"`, String(required), ...o.args.map((a) => id(a.name))].join(', ')
    return `    fun ${camel(o.op)}(${params}): JsonElement = go(${call})`
  })
  return `// Generated by tools/gen-door.cjs from sdk/door.table. Do not edit.
// Every op of the core's door as a function of its arguments by position (sdk/rust/src/door.rs).
package world.foodx.foodblock

import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull

internal object Door {
    /** One call; a missing (null) optional argument at the end is left out. */
    private fun go(op: String, required: Int, vararg args: JsonElement): JsonElement {
        var n = args.size
        while (n > required && args[n - 1] is JsonNull) n--
        return Native.invoke(op, *args.take(n).toTypedArray())
    }

${fns.join('\n')}
}
`
}
module.exports = { file: 'sdk/kotlin/foodblock/src/main/kotlin/world/foodx/foodblock/Door.kt', emit }
