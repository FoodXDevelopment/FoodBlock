// Python: sdk/python/foodblock/_door.py. Every op as a function of its arguments by position, snake_case as the op. A list of
// blocks is any collection (list()); the trailing optional (`?`) and suite arguments default to None. The core's failures raise (_core.py).
const KEYWORDS = new Set(['id', 'from', 'in', 'is', 'type', 'hash', 'open', 'list', 'sign', 'min', 'max'])
const id = (n) => (KEYWORDS.has(n) ? `${n}_` : n)

const normal = (a) => (a.type === 'blocks' ? (a.optional ? `None if ${id(a.name)} is None else _blocks(${id(a.name)})` : `_blocks(${id(a.name)})`) : id(a.name))

function emit(ops) {
  const fns = ops.map((o) => {
    let tail = o.args.length
    while (tail > 0 && (o.args[tail - 1].optional || o.args[tail - 1].type === 'suite')) tail--
    const params = o.args.map((a, i) => (i >= tail ? `${id(a.name)}=None` : id(a.name))).join(', ')
    const call = [`"${o.op}"`, ...o.args.map(normal)].join(', ')
    const noqa = o.op === 'open' || o.op === 'hash' ? '  # noqa: A001' : ''
    return `def ${o.op}(${params}):${noqa}\n    return call(${call})\n`
  })
  return `# Generated by tools/gen-door.cjs from sdk/door.table. Do not edit.
from ._core import call


def _blocks(blocks):
    # any collection of blocks; a dict (blocks by hash) is its values, as in the JavaScript SDK (never its keys)
    return list(blocks.values()) if isinstance(blocks, dict) else list(blocks)


${fns.join('\n\n')}`
}
module.exports = { file: 'sdk/python/foodblock/_door.py', emit }
