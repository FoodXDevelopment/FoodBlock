// Swift: sdk/swift/Sources/FoodBlock/Door.swift. Every op as one static throwing function of its arguments by position, typed; an
// optional argument defaults to nil. The conversion of the answer is the Core helper for its type (Core.swift).
const { camel } = require('./table.cjs')

const ARG = { text: 'String', int: 'Int', bool: 'Bool', block: 'JSON', object: 'JSON', blocks: '[JSON]', strings: '[String]', json: 'Any?', time: 'String', suite: 'String?', arrivals: '[String: String]?' }
const RESULT = { text: 'String', bool: 'Bool', int: 'Int', block: 'JSON', object: 'JSON', blocks: '[JSON]', strings: '[String]', refusals: '[JSON]', json: 'Any?' }
const AS = { text: 'String', block: 'JSON', object: 'JSON', blocks: '[JSON]', refusals: '[JSON]', strings: '[String]', bool: 'Bool' }

function param(a) {
  const t = ARG[a.type]
  const missing = a.optional || a.type === 'suite' || a.type === 'arrivals'
  if (t.endsWith('?')) return `_ ${camel(a.name)}: ${t}${missing ? ' = nil' : ''}`
  return `_ ${camel(a.name)}: ${t}${a.optional ? '? = nil' : ''}`
}

function body(o) {
  const args = [`"${o.op}"`, ...o.args.map((a) => camel(a.name))].join(', ')
  const r = o.result
  if (o.nullable) return r === 'json' ? `try Core.maybe(${args})` : `try Core.maybe(${args}) as? ${AS[r]}`
  switch (r) {
    case 'text': return `try Core.string(${args})`
    case 'bool': return `try Core.bool(${args})`
    case 'block': case 'object': return `try Core.json(${args})`
    case 'strings': return `try Core.strings(${args})`
    case 'blocks': case 'refusals': return `try Core.list(${args})`
    case 'json': return `try Core.maybe(${args})`
    case 'int': return `guard let v = intOf(try Core.maybe(${args})) else { throw FoodBlockError.invalid("foodblock: ${o.op} gave no whole number") }; return v`
  }
  throw new Error(`swift: result ${r}`)
}

function emit(ops) {
  const fns = ops.map((o) => {
    const ret = RESULT[o.result] + (o.nullable && !RESULT[o.result].endsWith('?') ? '?' : '')
    return `    static func ${camel(o.op)}(${o.args.map(param).join(', ')}) throws -> ${ret} { ${body(o)} }`
  })
  return `// Generated by tools/gen-door.cjs from sdk/door.table. Do not edit.
// Every op of the core's door (src/door.rs) as a static function of its arguments by position; a missing optional is nil.
import Foundation

enum Door {
${fns.join('\n')}
}
`
}
module.exports = { file: 'sdk/swift/Sources/FoodBlock/Door.swift', emit }
