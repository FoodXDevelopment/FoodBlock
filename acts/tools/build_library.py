# build_library.py: writes LIBRARY.md, every act grouped by verb, from acts.json and form.json.
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from moves import moves_for, fact_tags, other_sides, no_side_reason
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
GROUPS = [('Knowing', ['Find out', 'Tell', 'Log', 'Learn', 'Teach']),
          ('Exchanging', ['Buy', 'Sell', 'Swap', 'Lend', 'Borrow', 'Give', 'Get']),
          ('Complying', ['Comply']),
          ('Deciding', ['Set', 'Plan', 'Agree']),
          ('Sharing', ['Share']),
          ('Doing', ['Create', 'Make', 'Grow', 'Keep', 'Carry', 'Eat'])]
def library_md():
    """LIBRARY.md as built now from acts.json and form.json (check.py compares it with the committed one)."""
    acts = json.load(open(D + 'acts.json'))
    form = json.load(open(D + 'form.json'))
    assert sorted(sum((v for _, v in GROUPS), [])) == sorted(form['verbs']), 'GROUPS must hold every verb in form.json'
    out = ['# The act library', '',
           'Every act FoodOS can read, do or suggest, grouped by family. Each act carries its facts (what changes, who is in it, which way,',
           'what goes in exchange, how long it runs, consent, who waits, who carries the outcome, and for deals between separate plans the',
           'other side and how the price is set); its moves, in brackets, and its term rules are worked out from them. Rules: PATTERNS.md.',
           'Fields: FIELDS.md. The list is a cache of trusted names, not a gate: an act nobody has named yet still counts, shown by its parts.',
           'The family each act sits under (Buying, Selling, Giving and the rest) is a browsing label and nothing more: no rule reads it. Every rule is',
           'worked out from the facts. Each act has one "you do this when" line, what sets it apart from its neighbours. A deal is one act whoever',
           'signs it: an act that names both ends (`sides`, from and to) is read from whichever end signed, and an old name or id it took in is listed',
           'as "also called" and "was".',
           'Generated by tools/build_library.py from acts.json; do not edit by hand.', '',
           f'{len(acts)} acts, {len(form["verbs"])} families, {sum(len(a["examples"]) for a in acts)} examples.', '']
    for g, verbs in GROUPS:
        out.append(f'## {g}')
        for v in verbs:
            vs = [a for a in acts if a['verb'] == v]
            if not vs: continue
            out.append(f'\n### {v}')
            for a in vs:
                tag = fact_tags(a, form, {x['name']: x for x in acts})
                sides = other_sides(a, acts, form)
                if sides: tag.append(('other side: ' if 'mirror' in a else 'other side (from the facts): ') + ', '.join(sides))
                reason = a.get('no mirror') or (None if sides else no_side_reason(a, form))
                if reason: tag.append('no other side: ' + reason)
                out.append(f'- **{a["name"]}** ({" · ".join(tag)}). Card: "{a["card"]}"')
                if a.get('sides'): out.append(f'  Two ends of one deal: {a["sides"]["from"]} (gives) and {a["sides"]["to"]} (takes).')
                if a.get('you do this when'): out.append(f'  You do this when: {a["you do this when"]}')
                if a.get('known as'): out.append('  Also called: ' + '; '.join(a['known as']) + '.')
                if a.get('was'): out.append('  Was: ' + ', '.join(a['was']) + '.')
                out.append('  [' + ' · '.join(moves_for(a, form)[1]) + ']')
                out.append('  ' + a['note'].replace('\n', '\n  '))
                out.append(f'  Examples: {"; ".join(e["card"].rstrip(".") for e in a["examples"])}.')
                for w in a.get('move words', []):
                    out.append(f'  - Move words **{w["words"]}** ({" or ".join(w["moves"])}). Card: "{w["card"]}" {w["note"]}')
        out.append('')
    out.append('## On any deal')
    for w in form['moves']['on any deal']:
        out.append(f'- **{w["words"]}** ({" or ".join(w["moves"])}). Card: "{w["card"]}"')
        out.append('  ' + w['note'])
        out.append(f'  Examples: {"; ".join(e["card"].rstrip(".") for e in w["examples"])}.')
    out.append('')
    return '\n'.join(out) + '\n', len(acts)

if __name__ == '__main__':
    text, n = library_md()
    open(D + 'LIBRARY.md', 'w').write(text)
    print('wrote LIBRARY.md:', n, 'acts')
